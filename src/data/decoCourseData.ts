// Build 60 instructional dates from 03-Aug-2026 to 06-Nov-2026 (Mon-Fri with realistic spacing)
function buildLectureDates(): string[] {
  const start = new Date(Date.UTC(2026, 7, 3)); // 03-Aug-2026 (Monday)
  const end = new Date(Date.UTC(2026, 10, 6)); // 06-Nov-2026 (Friday)
  const months = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];
  const weekdays: Date[] = [];
  const cur = new Date(start);
  while (cur <= end) {
    const day = cur.getUTCDay();
    if (day >= 1 && day <= 5) {
      weekdays.push(new Date(cur));
    }
    cur.setUTCDate(cur.getUTCDate() + 1);
  }
  // Sample 60 evenly distributed instructional dates ensuring first is 03-Aug-2026 and last is 06-Nov-2026
  const selected: string[] = [];
  for (let i = 0; i < 60; i++) {
    const idx = Math.round((i * (weekdays.length - 1)) / 59);
    const d = weekdays[idx];
    const dd = String(d.getUTCDate()).padStart(2, '0');
    const mmm = months[d.getUTCMonth()];
    const yyyy = d.getUTCFullYear();
    selected.push(`${dd}-${mmm}-${yyyy}`);
  }
  return selected;
}

